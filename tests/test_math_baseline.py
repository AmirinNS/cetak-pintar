"""Regression baseline for math worksheet planning and content generation at seed=42.

Pins the exact sheet order and problem data generated by the unchanged codebase for:
- preset=t1&seed=42
- preset=t2&seed=42
- preset=t3&seed=42
- t=add,sifir_ref,sifir&sifir_tables=2,3&pages=4&seed=42

Mirrors the generation sequence in modules/render/pdf.py:render() lines 39-100.
"""

from __future__ import annotations

from dataclasses import asdict, is_dataclass
from random import Random
from typing import Any

from modules.layout import cards_per_sheet, plan_sheets
from modules.problems import (
    addition,
    counting,
    division,
    grid_blanks,
    multiplication,
    subtraction,
)
from modules.spec import Spec, parse_spec


def to_plain(obj: Any) -> Any:
    """Convert dataclasses to plain dicts recursively, leaving other primitives as-is."""
    if is_dataclass(obj):
        return asdict(obj)
    if isinstance(obj, list):
        return [to_plain(x) for x in obj]
    return obj


def generate_content_data(spec: Spec) -> dict[tuple[str, int], Any]:
    """Replicate the problem generation loop in modules/render/pdf.py."""
    sheets = plan_sheets(spec)
    seed = spec.seed if spec.seed is not None else 0
    rng = Random(seed)

    sheet_data: dict[tuple[str, int], Any] = {}
    for kind, topic, sheet_idx in sheets:
        if kind == "content":
            key = (topic, sheet_idx)
            if topic == "grid":
                sheet_data[key] = grid_blanks(rng, spec.grid_start, spec.grid_blanks)
            elif topic == "count":
                sheet_data[key] = counting(
                    rng, spec.count_max, spec.count_shapes, cards_per_sheet(spec, "count")
                )
            elif topic == "add":
                count = cards_per_sheet(spec, "add")
                sheet_data[key] = addition(rng, spec.add_digits, bool(spec.add_regroup), count)
            elif topic == "sub":
                count = cards_per_sheet(spec, "sub")
                sheet_data[key] = subtraction(rng, spec.sub_digits, bool(spec.sub_borrow), count)
            elif topic == "sifir_ref":
                sorted_tables = sorted(spec.sifir_tables)
                sheet_data[key] = sorted_tables[sheet_idx * 6 : (sheet_idx + 1) * 6]
            elif topic == "sifir":
                count = cards_per_sheet(spec, "sifir")
                sheet_data[key] = multiplication(rng, spec.sifir_tables, count)
            elif topic == "div":
                sheet_data[key] = division(
                    rng,
                    spec.div_digits,
                    spec.div_divisors,
                    bool(spec.div_rem),
                    cards_per_sheet(spec, "div"),
                )
    return {k: to_plain(v) for k, v in sheet_data.items()}


